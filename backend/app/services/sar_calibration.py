"""Sentinel-1 Level-1 GRD radiometric calibration: digital numbers to sigma nought.

ESA, "Radiometric Calibration of S-1 Level-1 Products Generated by the S-1 IPF"
(ESA-EOPG-CSCOP-TN-0002): sigma0 = |DN|^2 / A_sigma^2, where A_sigma comes from the
product's calibration annotation (``calibrationVectorList`` / ``sigmaNought``) and is
interpolated bilinearly in line and pixel. Thermal noise is not removed (declared): in
cross-polarisation over dry soil the result can sit near the noise floor (~ -22 dB).
"""
from __future__ import annotations

import xml.etree.ElementTree as ET
from dataclasses import dataclass

import numpy as np


@dataclass(frozen=True)
class CalibrationLut:
    lines: np.ndarray          # (n,) image line of each calibration vector
    pixels: list[np.ndarray]   # per vector, the pixel columns it samples
    sigma: list[np.ndarray]    # per vector, A_sigma at those columns


def parse_calibration(xml_bytes: bytes) -> CalibrationLut:
    """The sigma-nought LUT of a Sentinel-1 calibration annotation."""
    root = ET.fromstring(xml_bytes)
    vectors = root.findall(".//calibrationVectorList/calibrationVector")
    if not vectors:
        raise ValueError("calibration annotation has no calibrationVector")
    lines, pixels, sigma = [], [], []
    for v in vectors:
        px = np.array(v.findtext("pixel").split(), dtype=np.float64)
        sg = np.array(v.findtext("sigmaNought").split(), dtype=np.float64)
        if px.size != sg.size or px.size < 2:
            raise ValueError("calibration vector with mismatched pixel/sigmaNought lists")
        lines.append(float(v.findtext("line")))
        pixels.append(px)
        sigma.append(sg)
    order = np.argsort(lines)
    return CalibrationLut(np.array(lines)[order], [pixels[i] for i in order], [sigma[i] for i in order])


def sigma_coefficient(lut: CalibrationLut, rows: np.ndarray, cols: np.ndarray) -> np.ndarray:
    """A_sigma at image (row, col), bilinear between the bracketing calibration vectors."""
    rows = np.asarray(rows, dtype=np.float64)
    cols = np.asarray(cols, dtype=np.float64)
    along = np.vstack([np.interp(cols, px, sg) for px, sg in zip(lut.pixels, lut.sigma)])
    hi = np.clip(np.searchsorted(lut.lines, rows, side="right"), 1, len(lut.lines) - 1)
    lo = hi - 1
    span = lut.lines[hi] - lut.lines[lo]
    w = np.clip((rows - lut.lines[lo]) / np.where(span == 0, 1, span), 0.0, 1.0)
    idx = np.arange(rows.size)
    return (1 - w) * along[lo, idx] + w * along[hi, idx]


def sigma0_db(dn: np.ndarray, rows: np.ndarray, cols: np.ndarray, lut: CalibrationLut) -> np.ndarray:
    """Calibrated backscatter in dB; NaN where DN is 0 (no signal)."""
    dn = np.asarray(dn, dtype=np.float64)
    a = sigma_coefficient(lut, rows, cols)
    with np.errstate(divide="ignore", invalid="ignore"):
        lin = dn ** 2 / a ** 2
        out = 10.0 * np.log10(lin)
    out[~(dn > 0)] = np.nan
    return out


def zonal_db(values_db: np.ndarray) -> dict:
    """Parcel statistics of dB values: the mean is taken in linear power, then back to dB."""
    v = np.asarray(values_db, dtype=np.float64)
    v = v[np.isfinite(v)]
    if v.size == 0:
        return {"mean": None, "min": None, "max": None, "pixel_count": 0}
    return {"mean": float(10.0 * np.log10(np.mean(10.0 ** (v / 10.0)))),
            "min": float(np.min(v)), "max": float(np.max(v)), "pixel_count": int(v.size)}
